#!/bin/bash
#
# Supabase Type Generation
# Regenerates packages/database/src/types/generated.ts from the local Supabase DB.
#
# Usage:
#   ./scripts/generate-types.sh             # generates from local supabase (default)
#   SUPABASE_DB_URL=... ./scripts/generate-types.sh   # generates from a specific URL
#   ./scripts/generate-types.sh --check     # generates to a temp file and diffs against committed

set -euo pipefail

OUTPUT="packages/database/src/types/generated.ts"
SUPABASE_DB_URL="${SUPABASE_DB_URL:-postgresql://postgres:postgres@localhost:54322/postgres}"

if ! command -v supabase &> /dev/null; then
  echo "❌ Supabase CLI is not installed."
  echo "   macOS: brew install supabase/tap/supabase"
  echo "   Other: https://supabase.com/docs/guides/cli/getting-started"
  exit 1
fi

generate_to() {
  local out="$1"
  local tmp
  tmp="$(mktemp)"
  echo "/* eslint-disable */" > "$tmp"
  echo "// AUTOGENERATED — do not edit. Re-run \`pnpm db:types:generate\`." >> "$tmp"
  npx supabase gen types typescript --db-url "$SUPABASE_DB_URL" >> "$tmp"
  mv "$tmp" "$out"
}

if [ "${1:-}" = "--check" ]; then
  echo "🔍 Checking that committed types match the live schema..."
  TMP="$(mktemp)"
  generate_to "$TMP"
  if ! diff -q "$OUTPUT" "$TMP" >/dev/null; then
    echo "❌ Drift detected: $OUTPUT is out of sync with the database schema."
    echo "   Run: pnpm db:types:generate && commit the result."
    diff "$OUTPUT" "$TMP" | head -80
    rm -f "$TMP"
    exit 1
  fi
  rm -f "$TMP"
  echo "✅ Types are in sync with the schema."
  exit 0
fi

echo "🔄 Generating Supabase types → $OUTPUT"
generate_to "$OUTPUT"
echo "✅ Wrote $OUTPUT"
echo ""
echo "Next:"
echo "  - Commit the regenerated file in the same PR as your migration."
echo "  - Run 'pnpm build --filter=@gustri/database' to verify."
